#!/usr/bin/env bash
set -euo pipefail

# Usage:
#   bash plugins/lock.sh          Resolve plugins.txt and write plugins.lock.txt (needs Docker).
#   bash plugins/lock.sh --check  Check that plugins.lock.txt keeps every pin in plugins.txt.
#
# The resolve runs jenkins-plugin-cli in the Dockerfile base image, so it uses the
# same Jenkins core and tool version as the image build. Direct pins in plugins.txt
# stay as written; every dependency gets the newest version compatible with the core.
DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
TXT="$DIR/plugins.txt"
LOCK="$DIR/plugins.lock.txt"

entries() {
  sed -e 's/#.*//' -e 's/[[:space:]]//g' "$1" | grep -v '^$' || true
}

check() {
  local status=0 line name
  test -s "$LOCK" || { echo "Missing $LOCK. Run: bash plugins/lock.sh" >&2; exit 1; }
  if entries "$LOCK" | grep -Ev '^[A-Za-z0-9._-]+:[^:]+$' >&2; then
    echo "Each lock line must be name:version." >&2
    status=1
  fi
  if [ -n "$(entries "$LOCK" | cut -d: -f1 | sort | uniq -d)" ]; then
    echo "The lock lists a plugin more than once." >&2
    status=1
  fi
  while IFS= read -r line; do
    name=${line%%:*}
    if ! entries "$LOCK" | grep -Fxq "$line"; then
      echo "plugins.txt pins $line, but the lock has: $(entries "$LOCK" | grep "^$name:" || echo none)" >&2
      status=1
    fi
  done < <(entries "$TXT")
  if [ "$status" != 0 ]; then
    echo "Run: bash plugins/lock.sh" >&2
    exit 1
  fi
  echo "plugins.lock.txt keeps all $(entries "$TXT" | wc -l | tr -d ' ') pins ($(entries "$LOCK" | wc -l | tr -d ' ') plugins)."
}

if [ "${1:-}" = "--check" ]; then
  check
  exit 0
fi
[ $# = 0 ] || { echo "Usage: bash plugins/lock.sh [--check]" >&2; exit 2; }
command -v docker >/dev/null || { echo "Required tool: docker" >&2; exit 1; }

BASE=$(sed -n 's/^FROM[[:space:]]\{1,\}\([^[:space:]]*\).*/\1/p' "$DIR/Dockerfile" | head -n 1)
test -n "$BASE" || { echo "No FROM image in $DIR/Dockerfile" >&2; exit 1; }
OUT=$(mktemp)
ERR=$(mktemp)
NEW=$(mktemp)
trap 'rm -f "$OUT" "$ERR" "$NEW"' EXIT

if ! docker run --rm --mount "type=bind,src=$TXT,dst=/tmp/plugins.txt,readonly" \
  --entrypoint jenkins-plugin-cli "$BASE" \
  --plugin-file /tmp/plugins.txt --latest true --no-download --list > "$OUT" 2> "$ERR"; then
  cat "$ERR" >&2
  exit 1
fi

{
  echo "# Generated by plugins/lock.sh from plugins.txt. Do not edit by hand."
  echo "# Base image: $BASE"
  awk '/^Resulting plugin list:/ { found = 1; next }
       found && NF == 2 { print $1 ":" $2; next }
       found { exit }' "$OUT" | sort
} > "$NEW"
[ "$(entries "$NEW" | wc -l)" -gt 0 ] || { cat "$OUT" >&2; echo "No resolved plugin list." >&2; exit 1; }
mv "$NEW" "$LOCK"
check
